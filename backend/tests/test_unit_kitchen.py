import asyncio
import json

from app.services.kitchen import KitchenService, find_violations, normalize_recipe, scale_recipe
from app.utils.errors import AppError, ProviderError

import pytest
from tests.helpers import FakeLLM

REQ = dict(ingredients=["broccoli", "rice"], equipment=[], diet="omnivore", restrictions=[], avoid=[], dish=None, servings=None, notes=None)

GOOD = {"recipes": [{"title": "Veg bowl", "servings": 2, "prep_minutes": 5, "cook_minutes": 10, "difficulty": "easy",
                     "ingredients": [{"name": "broccoli", "quantity": 200, "unit": "g"}, {"name": "rice", "quantity": 150, "unit": "g"}],
                     "steps": ["Cook rice.", "Steam broccoli."], "safety_notes": []}]}


def run(svc, **kw):
    return asyncio.run(svc.recipes(**{**REQ, **kw}))


def test_fallback_without_llm_is_clearly_labelled():
    r = run(KitchenService(FakeLLM(available=False)))
    assert r["source"] == "local_fallback" and "NOT generated by an AI" in r["source_label"]
    assert r["fallback_reason"] and r["recipes"]


def test_llm_success_path_and_label():
    r = run(KitchenService(FakeLLM(json.dumps(GOOD))))
    assert r["source"] == "llm" and r["recipes"][0]["title"] == "Veg bowl" and r["fallback_reason"] is None


def test_llm_timeout_falls_back_with_reason():
    r = run(KitchenService(FakeLLM(error=ProviderError("The AI provider timed out. Please try again."))))
    assert r["source"] == "local_fallback" and "timed out" in r["fallback_reason"]


def test_llm_garbage_falls_back():
    assert run(KitchenService(FakeLLM("lol not json")))["source"] == "local_fallback"
    assert run(KitchenService(FakeLLM('{"recipes":[{"title":"x"}]}')))["source"] == "local_fallback"


def test_llm_recipe_violating_diet_is_discarded():
    bad = {"recipes": [{**GOOD["recipes"][0], "ingredients": [{"name": "chicken breast", "quantity": 200, "unit": "g"}]}]}
    r = run(KitchenService(FakeLLM(json.dumps(bad))), diet="vegan")
    assert r["source"] == "local_fallback" and "dietary rules" in r["fallback_reason"]
    assert all(not find_violations(x, "vegan", [], []) for x in r["recipes"])


def test_fallback_respects_diet_restrictions_and_avoid():
    svc = KitchenService(FakeLLM(available=False))
    r = run(svc, diet="vegan", restrictions=["gluten_free"], avoid=["soy"])
    ids = [x["id"] for x in r["recipes"]]
    assert ids == ["tomato-lentil-soup"]
    r = run(svc, diet="vegan")
    assert all(x["id"] not in ("chicken-veg-skillet", "egg-fried-rice") for x in r["recipes"])


def test_no_match_returns_empty_with_message_not_a_violating_recipe():
    r = run(KitchenService(FakeLLM(available=False)), diet="vegan", restrictions=["gluten_free", "soy_free", "nut_free"], avoid=["lentil", "tomato"])
    assert r["recipes"] == [] and r["notes"]


def test_scaling():
    base = normalize_recipe(GOOD["recipes"][0])
    s = scale_recipe(base, 6)
    assert s["servings"] == 6 and s["ingredients"][0]["quantity"] == 600 and base["ingredients"][0]["quantity"] == 200
    for bad in (0, 51):
        with pytest.raises(AppError):
            scale_recipe(base, bad)


def test_chat_fallback_labelled_and_llm_path():
    reply = asyncio.run(KitchenService(FakeLLM(available=False)).chat([{"role": "user", "content": "what temperature is chicken done?"}], None))
    assert reply["source"] == "local_fallback" and "74 C" in reply["reply"] and "not an AI" in reply["reply"]
    reply = asyncio.run(KitchenService(FakeLLM("Use medium heat.")).chat([{"role": "user", "content": "hi"}], None))
    assert reply["source"] == "llm" and reply["reply"] == "Use medium heat."
